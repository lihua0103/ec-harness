import type { RuntimeSpec } from './runner.js';
import type { Scenario, PkType } from './knowledge.js';
const digest=(b:Buffer|string)=>createHash('sha256').update(b).digest('hex');
export interface ArtifactCheck {
  version:string; passed:true; xlsxDigest:string; rdsDigest:string; checkerDigest:string;
  dependencies:Record<string,string>;
}
export function rdsCheckerScript(scenario:Scenario,pkType?:PkType):string {
  const contract=outputContract(scenario,pkType);
  // Names and types originate only from fixed host contracts, never tool/model strings.
  return `${dependencyProbeR}
con <- file("output.rds", "rb")
x <- readRDS(con)
if (length(readBin(con, "raw", n=1L))) stop("RDS_TRAILING_BYTES")
close(con)
if (!identical(class(x), "data.frame") || !identical(sort(names(attributes(x))), sort(c("names","row.names","class")))) stop("RDS_CLASS")
expected <- c(${contract.columns.map(c=>JSON.stringify(c.name)).join(',')})
if (!identical(names(x), expected) || nrow(x)>10000L || ncol(x)>128L) stop("RDS_SHAPE")
types <- c(${contract.columns.map(c=>JSON.stringify(c.type)).join(',')})
nullable <- c(${contract.columns.map(c=>c.nullable?'TRUE':'FALSE').join(',')})
expected_csv <- read.csv("output.csv", colClasses="character", na.strings=NULL, check.names=FALSE)
if (nrow(x)!=nrow(expected_csv)) stop("RDS_ROWS")
for (j in seq_along(x)) {
  v <- x[[j]]
  if (!is.null(attributes(v)) || !is.atomic(v)) stop("RDS_ATTRIBUTES")
  if (types[j] == "numeric") {
    if (!(typeof(v) %in% c("integer","double")) || any(!is.finite(v))) stop("RDS_NUMERIC_TYPE")
  } else if (!identical(typeof(v), types[j])) stop("RDS_COLUMN_TYPE")
  if (!nullable[j] && anyNA(v)) stop("RDS_MISSING")
  if (nullable[j] && !identical(is.na(v), expected_csv[[j]] == "")) stop("RDS_MISSING_REPRESENTATION")
  if (is.character(v) && (any(nchar(v, type="bytes")>12000L,na.rm=TRUE) || any(grepl("^[[:space:]]*[=+@]",v),na.rm=TRUE))) stop("RDS_TEXT")
}
# Canonical output is generated by the checker, not read from a model-provided report.
options(digits=17)
write.table(x, file=stdout(), sep=",", row.names=FALSE, col.names=TRUE, quote=TRUE, na="", qmethod="double")
`;
}
async function checkRds(runtime:RuntimeSpec,rds:Buffer,csv:string,script:string,signal?:AbortSignal):Promise<string> {
  // Only uncompressed XDR v2 is admitted. Bounds compressed-bomb risk before R deserialization.
  if(rds.length>1024*1024 || rds.length<14 || rds.subarray(0,2).toString()!=='X\n' || rds.readInt32BE(2)!==2) throw new ListingError('OUTPUT_RDS_SERIALIZATION');
  const root=await mkdtemp(join(tmpdir(),'listing-independent-qc-'));
  try {
    await writeFile(join(root,'output.rds'),rds,{flag:'wx'});
    await writeFile(join(root,'output.csv'),csv,{flag:'wx'});
    await writeFile(join(root,'check.R'),script,{flag:'wx'});
    return await new Promise<string>((resolve,reject)=>{
      if(signal?.aborted){reject(new ListingError('CANCELLED'));return;}
      const args=runtime.kind==='Rterm'?['--vanilla','--slave','--file=check.R']:['--vanilla','check.R'];
      const child=spawn(runtime.executable,args,{cwd:root,env:runtimeEnvironment(runtime,root),shell:false,windowsHide:true});
      const chunks:Buffer[]=[];let size=0,failure:string|undefined,stderr='';
      const fail=(code:string)=>{if(!failure){failure=code;child.kill('SIGKILL');}};
      const timer=setTimeout(()=>fail('OUTPUT_RDS_CHECK_TIMEOUT'),10000);
      const abort=()=>fail('CANCELLED');signal?.addEventListener('abort',abort,{once:true});
      child.stdout.on('data',(b:Buffer)=>{size+=b.length;if(size>1024*1024)fail('OUTPUT_RDS_CHECK_LIMIT');else chunks.push(b);});
      // Real checker errors are kept bounded and surface in the failure detail for autonomous debugging.
      child.stderr.on('data',(b:Buffer)=>{if(stderr.length<4096)stderr+=b.toString('utf8');});
      child.once('error',()=>{clearTimeout(timer);signal?.removeEventListener('abort',abort);fail('OUTPUT_RDS_CHECK_UNAVAILABLE');});
      child.once('close',code=>{clearTimeout(timer);signal?.removeEventListener('abort',abort);
        const detail=stderr.trim()?': '+stderr.trim().slice(-800):'';
        if(failure){reject(new ListingError(failure+detail));return;}
        if(code!==0)reject(new ListingError('OUTPUT_RDS_CONTRACT_FAILED'+detail));
        else resolve(Buffer.concat(chunks).toString('utf8'));
      });
    });
  } finally {await rm(root,{recursive:true,force:true});}
}
function matches(a:string,b:string,type:string):boolean {
  if(type==='numeric')return a.trim()!==''&&b.trim()!==''&&Number.isFinite(Number(a))&&Number.isFinite(Number(b))&&Math.abs(Number(a)-Number(b))<=1e-10;
  return a===b;
}
/** Also reused during delivery without launching any executable from a persisted path. */
export async function verifyExcel(scenario:Scenario,pkType:PkType|undefined,csv:string,xlsx:Buffer):Promise<void> {
  const contract=outputContract(scenario,pkType),table=parseCsv(csv);
  if(JSON.stringify(table[0])!==JSON.stringify(contract.columns.map(c=>c.name)))throw new ListingError('OUTPUT_COLUMNS_INVALID');
  const wb=await Workbook.open(xlsx);
  let cells:Awaited<ReturnType<Workbook['readOutputTable']>>;
  try{cells=await wb.readOutputTable();}finally{wb.close();}
  const map=new Map(cells.map(c=>[c.ref,c]));
  for(let r=0;r<table.length;r++)for(let c=0;c<contract.columns.length;c++) {
    const ref=`${String.fromCharCode(65+c)}${r+1}`,cell=map.get(ref),column=contract.columns[c];map.delete(ref);
    const expected=table[r][c];
    if(r>0&&column.nullable&&expected===''){
      if(cell && !(cell.type==='blank'||cell.type==='character'&&cell.value===''))throw new ListingError('OUTPUT_XLSX_MISSING_MISMATCH');
    } else if(!cell||cell.type!==(r===0?'character':column.type)||!matches(cell.value,expected,r===0?'character':column.type))throw new ListingError('OUTPUT_XLSX_CONTRACT_FAILED');
  }
  // Blank cells outside the defined rectangle are also rejected; no silent trailing rows/columns.
  if(map.size)throw new ListingError('OUTPUT_XLSX_EXTRA_CELLS');
}
/** CSV is independently business-checked by caller; compare all formats and explicit types. */
export async function verifyArtifacts(scenario:Scenario,pkType:PkType|undefined,csv:string,xlsx:Buffer,rds:Buffer,runtime:RuntimeSpec,signal?:AbortSignal):Promise<ArtifactCheck> {
  await verifyExcel(scenario,pkType,csv,xlsx);
  const contract=outputContract(scenario,pkType),table=parseCsv(csv);
  const script=rdsCheckerScript(scenario,pkType);
  const rdsTable=parseCsv(await checkRds(runtime,rds,csv,script,signal));
  if(rdsTable.length!==table.length||rdsTable.some((row,r)=>row.length!==table[r].length||row.some((v,c)=>!matches(v,table[r][c],r===0?'character':contract.columns[c].type)))) throw new ListingError('OUTPUT_RDS_VALUE_MISMATCH');
  if(signal?.aborted)throw new ListingError('CANCELLED');
  return {version:OUTPUT_CONTRACT_VERSION,passed:true,xlsxDigest:digest(xlsx),rdsDigest:digest(rds),checkerDigest:digest(script),dependencies:{...contract.dependencies}};
}
